"""Refresh the bundled map snapshot from a Google My Maps export.
In My Maps: ⋮ → Export to KMZ → (whole map) → Download. Then run:
    python3 tools/kmz-to-js.py path/to/IIM_Kozhikode.kmz
It rewrites mymap-data.js (the map shown instantly/offline before the live map loads)."""
import sys, zipfile, re, json, base64, datetime, xml.etree.ElementTree as ET
IST = datetime.timezone(datetime.timedelta(hours=5, minutes=30))
ns = {"k": "http://www.opengis.net/kml/2.2"}
z = zipfile.ZipFile(sys.argv[1]); kml_name = next(n for n in z.namelist() if n.endswith(".kml"))
raw = z.read(kml_name).decode("utf-8"); doc = ET.fromstring(raw.encode()).find("k:Document", ns)
icons = {}
for s in doc.findall("k:Style", ns):
    href = s.findtext(".//k:Icon/k:href", namespaces=ns)
    if not href or href not in z.namelist(): continue
    base = re.sub(r"-(nodesc|normal|highlight)", "", s.get("id"))
    if base in icons: continue
    pin = base.startswith("icon-ci-") or base.startswith("icon-1899")
    icons[base] = {"src": "data:image/png;base64," + base64.b64encode(z.read(href)).decode(), "pin": pin}
as_of = datetime.datetime.now(IST).strftime("%d %b %Y")
out = ("/* Snapshot of the IIMK Google My Map with its icons (generated by tools/kmz-to-js.py).\n"
       "   Shown instantly/offline; the live map from /api/mymap replaces it when it loads. */\n"
       "window.MYMAP = " + json.dumps({"kml": raw, "icons": icons, "asOf": as_of}, ensure_ascii=False) + ";\n")
open("mymap-data.js", "w", encoding="utf-8").write(out)
print(f"mymap-data.js updated: {len(icons)} icons, as of {as_of}")
